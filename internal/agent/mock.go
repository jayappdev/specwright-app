// Mock is a scripted agent for demos, tests and machines without a CLI. It
// really writes the Spec Kit files it says it writes (so the watcher sees
// them) and really calls extensions through the loopback bridge.
//
// Prompt markers change its behaviour: "[mock:loop]" repeats one tool call
// forever (to trip loop detection) and "[mock:fail]" exits with an error.
type Mock struct {
	Delay time.Duration // pause between events (default 250ms)
}

// NewMock returns the mock driver.
func NewMock() *Mock { return &Mock{Delay: 250 * time.Millisecond} }

// Name implements Driver.
func (m *Mock) Name() string { return "mock" }

// Status implements Driver.
func (m *Mock) Status(context.Context) Status {
	return Status{Name: "mock", Label: "Mock agent (no CLI)", Available: true, Version: "scripted", Billing: "usd"}
}

