// Command gen-builtins writes the built-in tool catalog (names, descriptions,
// schemas) to frontend/src/builtins.generated.js for the browser preview.
//
//	go run ./scripts/gen-builtins
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"codegen/internal/builtin"
)

func main() {
	type info struct {
		Name        string         `json:"name"`
		Title       string         `json:"title"`
		Group       string         `json:"group"`
		Description string         `json:"description"`
		InputSchema map[string]any `json:"inputSchema"`
		ReadOnly    bool           `json:"readOnly"`
		Enabled     bool           `json:"enabled"`
	}
	var out []info
	for _, t := range builtin.Tools() {
		out = append(out, info{t.Name, t.Title, t.Group, t.Desc, t.Schema, t.ReadOnly, true})
	}
	b, _ := json.MarshalIndent(out, "", "  ")
	src := "// Generated by `go run ./scripts/gen-builtins` from internal/builtin. Do not edit.\nexport const BUILTINS = " + string(b) + ";\n"
	if err := os.WriteFile("frontend/src/builtins.generated.js", []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d built-in tools\n", len(out))
}
